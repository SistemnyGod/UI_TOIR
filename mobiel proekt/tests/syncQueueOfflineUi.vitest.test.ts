import { SyncQueueScreen } from '@/features/syncQueue/SyncQueueScreen';
import React from 'react';
import { act, create, type ReactTestRenderer } from 'react-test-renderer';
import { afterEach, beforeEach, expect, it, vi } from 'vitest';
const s = vi.hoisted(() => ({ sync: vi.fn() }));
vi.mock('react-native', () => ({ Text: 'Text', View: 'View', Pressable: 'Pressable', ActivityIndicator: 'ActivityIndicator', StyleSheet: { create: (s: any) => s } }));
vi.mock('@expo/vector-icons', () => ({ Ionicons: 'Icon' }));
vi.mock('expo-router', async () => { const R = await import('react'); return { useRouter: () => ({ push: vi.fn() }), useFocusEffect: (fn: any) => R.useEffect(fn, [fn]) }; });
vi.mock('@/features/settings/themePreference', () => ({ useAppTheme: () => ({ colors: {} }) }));
vi.mock('@/auth/dataOwnerContext', () => ({ captureDataOwnerContext: async () => ({ ownerUserId: 'owner', contourId: 'test', generation: 1 }), assertDataOwnerContext: async () => {}, StaleDataOwnerContextError: class extends Error {} }));
vi.mock('@/auth/tokenStorage', () => ({ getStoredOwnerUserId: async () => 'owner' }));
vi.mock('@/db/repositories/outboxRepository', () => ({ listSyncQueueCommands: async () => [{ clientOperationId: 'report-id', commandType: 'completePatrolAssignment', status: 'waiting_network', attemptCount: 0, assignmentRouteName: 'Помол', createdAtLocal: '2026-09-29T00:00:00Z' }] }));
vi.mock('@/db/repositories/filesRepository', () => ({ listSyncQueueFiles: async () => [] }));
vi.mock('@/sync/syncTriggers', () => ({ requestMobileDataRefresh: vi.fn(), triggerForegroundSyncWithRetry: s.sync }));
vi.mock('@/sync/syncEvents', () => ({ subscribeToSyncEvents: () => () => {} }));
vi.mock('@/services/mobileErrorReporter', () => ({ logMobileError: vi.fn() }));
vi.mock('@/services/patrolContinuationService', () => ({ continuePatrolWithReconciliation: vi.fn() }));
vi.mock('@/services/conflictResolutionService', () => ({ acceptServerConflict: vi.fn(), canAcceptServerConflict: () => false, cancelRejectedCommand: vi.fn(), retryConflictWithLatestRevision: vi.fn(), sendConflictToDispatcher: vi.fn() }));
vi.mock('@/ui/Card', () => ({ Card: 'Card' }));
vi.mock('@/ui/Screen', () => ({ Screen: 'Screen' }));
vi.mock('@/ui/PrimaryButton', () => ({ PrimaryButton: 'PrimaryButton' }));
vi.mock('@/ui/StatusPill', () => ({ StatusPill: 'StatusPill' }));
vi.mock('@/ui/ActionSheet', () => ({ ActionSheet: 'ActionSheet' }));
let screen: ReactTestRenderer;
beforeEach(() => { (globalThis as any).IS_REACT_ACT_ENVIRONMENT = true; s.sync.mockReset(); });
afterEach(async () => { await act(() => screen?.unmount()); });
it('a report waiting for network keeps manual retry available and blocks double taps', async () => {
  let finish!: (value: any) => void;
  s.sync.mockImplementation(() => new Promise(resolve => { finish = resolve; }));
  await act(async () => { screen = create(React.createElement(SyncQueueScreen)); });
  const retry = screen.root.findAllByType('PrimaryButton' as any).find(node => node.props.label === 'Отправить сейчас');
  expect(retry).toBeDefined();
  await act(async () => { retry!.props.onPress(); retry!.props.onPress(); });
  expect(s.sync).toHaveBeenCalledExactlyOnceWith({ mode: 'manualAll' });
  await act(async () => finish({ skipped: 'offline' }));
  expect(screen.root.findAllByType('PrimaryButton' as any).find(node => node.props.label === 'Отправить сейчас')!.props.disabled).toBe(false);
});
